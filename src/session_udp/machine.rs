//! UDP Session state machine.
//!
//! Pure logic module: no gpui, no tokio, and no clock or random source of its
//! own. Time arrives from outside (`now`, Unix seconds) and so do the random
//! bytes (the 32-byte handshake nonce). The whole machine is therefore
//! deterministic and testable without a network.
//!
//! Handshake (protocol §5.4, spec B):
//! `HELLO` → `CHALLENGE` → `RESPONSE` → `SESSION_OK`, or `SESSION_ERR`.

use crate::session_udp::codec::{
    Body, Frame, HANDSHAKE_NONCE_LEN, HKDF_INFO, Header, PacketType, decode, proof_a_input,
    proof_b_input,
};
use crate::session_udp::crypto::{hkdf_sha256, hmac_sha256, hmac_verify};
use std::fmt;

/// State machine input.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Command {
    /// Start the handshake: client nonce, pre-shared secret, HELLO resend count.
    Start {
        /// 32 random bytes, generated by the caller.
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        /// Pre-shared secret; its bytes are the HMAC key as they are.
        psk: String,
        /// Resend count after the first HELLO.
        hello_retries: u8,
    },
    /// Handshake timeout, driven by an external timer.
    Tick,
    /// A frame that arrived.
    Packet(Frame),
}

/// State machine output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Action {
    /// A frame that has to go out.
    Send(Frame),
    /// The handshake is over, the session is open.
    Established {
        /// Session id of the open session.
        session_id: u16,
    },
    /// Fatal failure: the connection ends.
    Failed(String),
}

/// Internal state.
enum State {
    Idle,
    /// Handshake in progress. The nonce stays the same across retries.
    Handshake {
        /// The client nonce of this attempt.
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        /// Pre-shared secret, kept until the session key is derived.
        psk: String,
        /// Resends left after the first HELLO.
        tries_left: u8,
        /// Nonce of the challenge that was answered; the session key needs it.
        nonce_b: Option<[u8; HANDSHAKE_NONCE_LEN]>,
    },
    /// The session is open.
    Established {
        /// Session id of the open session.
        session_id: u16,
        /// Session key. The encrypted frames of part C need it, so it is
        /// derived already here (spec B, §9).
        #[allow(dead_code)]
        key: [u8; 32],
        /// Sequence number of the next outgoing frame (spec B, §9).
        tx_seq: u32,
    },
    Failed,
}

/// UDP Session state machine.
pub struct Machine {
    state: State,
}

impl Machine {
    /// A machine that has not started yet.
    pub fn new() -> Self {
        Machine { state: State::Idle }
    }

    /// Handle one input and return the actions it produced.
    ///
    /// `now` is the Unix second the client clock reads; it fills the timestamp
    /// of outgoing frames.
    pub fn handle(&mut self, cmd: Command, now: u32) -> Vec<Action> {
        match cmd {
            Command::Start {
                nonce_a,
                psk,
                hello_retries,
            } => self.on_start(nonce_a, psk, hello_retries, now),
            Command::Tick => self.on_tick(now),
            Command::Packet(frame) => self.on_packet(frame, now),
        }
    }

    /// Handle one received datagram: parse it first, and decide by the current
    /// state whether a broken frame is a failure or is dropped silently.
    pub fn on_datagram(&mut self, bytes: &[u8], now: u32) -> Vec<Action> {
        match decode(bytes) {
            Ok(frame) => self.handle(Command::Packet(frame), now),
            // A frame that cannot be parsed is dropped silently: the device
            // stays silent on garbage too, and answering it would only feed a
            // noise peer (spec B, §8).
            Err(_) => Vec::new(),
        }
    }

    /// Start the handshake: only from `Idle`.
    fn on_start(
        &mut self,
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        psk: String,
        hello_retries: u8,
        now: u32,
    ) -> Vec<Action> {
        if !matches!(self.state, State::Idle) {
            return Vec::new();
        }
        // An empty secret is not a key: the attempt fails before a single byte
        // reaches the network.
        if psk.is_empty() {
            self.state = State::Failed;
            return vec![Action::Failed("empty psk".to_string())];
        }
        self.state = State::Handshake {
            nonce_a,
            psk,
            tries_left: hello_retries,
            nonce_b: None,
        };
        vec![Action::Send(Self::hello_frame(nonce_a, now))]
    }

    /// Handshake timeout: resend the same HELLO, and fail when the resends are
    /// used up.
    fn on_tick(&mut self, now: u32) -> Vec<Action> {
        let (nonce_a, tries_left) = match &self.state {
            State::Handshake {
                nonce_a,
                tries_left,
                ..
            } => (*nonce_a, *tries_left),
            _ => return Vec::new(),
        };
        if tries_left == 0 {
            self.state = State::Failed;
            return vec![Action::Failed("handshake timeout".to_string())];
        }
        if let State::Handshake {
            tries_left,
            nonce_b,
            ..
        } = &mut self.state
        {
            *tries_left -= 1;
            // The resend restarts the attempt: the device replaces its
            // challenge, so the answered challenge is not valid any more.
            *nonce_b = None;
        }
        vec![Action::Send(Self::hello_frame(nonce_a, now))]
    }

    /// The HELLO frame of an attempt.
    fn hello_frame(nonce_a: [u8; HANDSHAKE_NONCE_LEN], now: u32) -> Frame {
        Frame {
            header: Header {
                packet_type: PacketType::Hello,
                session_id: 0,
                seq: 0,
                timestamp: now,
            },
            body: Body::Hello { nonce_a },
        }
    }

    /// A frame that arrived: dispatch by the current state.
    fn on_packet(&mut self, frame: Frame, now: u32) -> Vec<Action> {
        if matches!(self.state, State::Handshake { .. }) {
            let (nonce_a, psk, tries_left, nonce_b) =
                match std::mem::replace(&mut self.state, State::Idle) {
                    State::Handshake {
                        nonce_a,
                        psk,
                        tries_left,
                        nonce_b,
                    } => (nonce_a, psk, tries_left, nonce_b),
                    other => {
                        self.state = other;
                        return Vec::new();
                    }
                };
            let (state, actions) =
                Self::handshake_packet(frame, nonce_a, psk, tries_left, nonce_b, now);
            self.state = state;
            actions
        } else {
            // After the handshake only encrypted frames arrive, and those are
            // part of the protocol of part C.
            Vec::new()
        }
    }

    /// A frame that arrived while the handshake is running.
    fn handshake_packet(
        frame: Frame,
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        psk: String,
        tries_left: u8,
        nonce_b: Option<[u8; HANDSHAKE_NONCE_LEN]>,
        now: u32,
    ) -> (State, Vec<Action>) {
        match frame.body {
            Body::Challenge {
                nonce_b: device_nonce,
                proof_b,
            } => {
                // The device proves that it knows the secret. Without this
                // check the client would answer a stranger.
                let input = proof_b_input(&nonce_a, &device_nonce);
                if !hmac_verify(psk.as_bytes(), &input, &proof_b) {
                    return (State::Failed, vec![Action::Failed("bad proof".to_string())]);
                }
                // The client proves the same, with the other context byte.
                let proof_a = hmac_sha256(psk.as_bytes(), &proof_a_input(&device_nonce, &nonce_a));
                let response = Frame {
                    header: Header {
                        packet_type: PacketType::Response,
                        session_id: 0,
                        seq: 0,
                        timestamp: now,
                    },
                    body: Body::Response { proof_a },
                };
                (
                    State::Handshake {
                        nonce_a,
                        psk,
                        tries_left,
                        nonce_b: Some(device_nonce),
                    },
                    vec![Action::Send(response)],
                )
            }
            Body::SessionOk => {
                // The session key needs the nonce of the challenge that was
                // answered. A SESSION_OK without a challenge is not ours.
                let Some(device_nonce) = nonce_b else {
                    return (
                        State::Handshake {
                            nonce_a,
                            psk,
                            tries_left,
                            nonce_b,
                        },
                        Vec::new(),
                    );
                };
                let mut salt = Vec::with_capacity(HANDSHAKE_NONCE_LEN * 2);
                salt.extend_from_slice(&nonce_a);
                salt.extend_from_slice(&device_nonce);
                let key = hkdf_sha256(psk.as_bytes(), &salt, HKDF_INFO);
                let session_id = frame.header.session_id;
                (
                    State::Established {
                        session_id,
                        key,
                        // The device numbers its own frames from 1, so the
                        // client starts there too.
                        tx_seq: 1,
                    },
                    vec![Action::Established { session_id }],
                )
            }
            Body::SessionErr { code } => (
                State::Failed,
                vec![Action::Failed(format!("session err {code}"))],
            ),
            // Every other frame is a passer-by: it does not belong to the
            // handshake and is dropped silently.
            _ => (
                State::Handshake {
                    nonce_a,
                    psk,
                    tries_left,
                    nonce_b,
                },
                Vec::new(),
            ),
        }
    }
}

impl Default for Machine {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Debug for Machine {
    /// Only the state name and the counters are printed: secret, key, nonce
    /// and proof never reach the log.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.state {
            State::Idle => write!(f, "Machine(Idle)"),
            State::Handshake { tries_left, .. } => {
                write!(f, "Machine(Handshake, tries_left={tries_left})")
            }
            State::Established {
                session_id, tx_seq, ..
            } => write!(
                f,
                "Machine(Established, session_id={session_id}, tx_seq={tx_seq})"
            ),
            State::Failed => write!(f, "Machine(Failed)"),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::session_udp::codec::PROOF_LEN;

    const PSK: &str = "super-secret-psk";
    const NOW: u32 = 1_700_000_000;
    const SESSION_ID: u16 = 9;

    fn nonce_a() -> [u8; HANDSHAKE_NONCE_LEN] {
        [7u8; HANDSHAKE_NONCE_LEN]
    }

    fn nonce_b() -> [u8; HANDSHAKE_NONCE_LEN] {
        [4u8; HANDSHAKE_NONCE_LEN]
    }

    fn start(m: &mut Machine) -> Vec<Action> {
        m.handle(
            Command::Start {
                nonce_a: nonce_a(),
                psk: PSK.into(),
                hello_retries: 3,
            },
            NOW,
        )
    }

    /// The challenge the device sends, with a correct proof.
    fn challenge() -> Frame {
        let proof_b = hmac_sha256(PSK.as_bytes(), &proof_b_input(&nonce_a(), &nonce_b()));
        Frame {
            header: Header {
                packet_type: PacketType::Challenge,
                session_id: 0,
                seq: 0,
                timestamp: NOW,
            },
            body: Body::Challenge {
                nonce_b: nonce_b(),
                proof_b,
            },
        }
    }

    fn session_ok() -> Frame {
        Frame {
            header: Header {
                packet_type: PacketType::SessionOk,
                session_id: SESSION_ID,
                seq: 0,
                timestamp: NOW,
            },
            body: Body::SessionOk,
        }
    }

    /// Run the handshake to an open session.
    fn establish(m: &mut Machine) {
        let hello = start(m);
        assert!(matches!(hello[0], Action::Send(_)));
        let challenge = challenge();
        let response = m.handle(Command::Packet(challenge), NOW);
        assert!(matches!(response[0], Action::Send(_)));
        let ok = m.handle(Command::Packet(session_ok()), NOW);
        assert!(
            ok.iter().any(
                |a| matches!(a, Action::Established { session_id } if *session_id == SESSION_ID)
            )
        );
    }

    /// The frame the machine sent, or a panic.
    fn sent(actions: &[Action]) -> &Frame {
        match &actions[0] {
            Action::Send(frame) => frame,
            other => panic!("expected a frame to send, got {other:?}"),
        }
    }

    #[test]
    fn happy_path_opens_the_session() {
        let mut m = Machine::new();
        let hello = start(&mut m);
        let frame = sent(&hello);
        assert_eq!(frame.header.packet_type, PacketType::Hello);
        assert_eq!(frame.header.session_id, 0);
        assert_eq!(frame.header.seq, 0);
        assert_eq!(frame.header.timestamp, NOW);
        let Body::Hello {
            nonce_a: sent_nonce,
        } = &frame.body
        else {
            panic!("expected a HELLO body");
        };
        assert_eq!(*sent_nonce, nonce_a());

        // The challenge is answered with a RESPONSE that carries proof_a.
        let challenge = challenge();
        let actions = m.handle(Command::Packet(challenge), NOW);
        let frame = sent(&actions);
        assert_eq!(frame.header.packet_type, PacketType::Response);
        let Body::Response { proof_a } = &frame.body else {
            panic!("expected a RESPONSE body");
        };
        let expected = hmac_sha256(PSK.as_bytes(), &proof_a_input(&nonce_b(), &nonce_a()));
        assert_eq!(*proof_a, expected);

        // SESSION_OK opens the session.
        let ok = m.handle(Command::Packet(session_ok()), NOW);
        assert!(
            ok.iter().any(
                |a| matches!(a, Action::Established { session_id } if *session_id == SESSION_ID)
            )
        );
    }

    #[test]
    fn session_err_does_not_open_the_session() {
        let mut m = Machine::new();
        let _ = start(&mut m);
        let err = Frame {
            header: Header {
                packet_type: PacketType::SessionErr,
                session_id: 0,
                seq: 0,
                timestamp: NOW,
            },
            body: Body::SessionErr { code: 2 },
        };
        let actions = m.handle(Command::Packet(err), NOW);
        assert!(matches!(&actions[..], [Action::Failed(text)] if text == "session err 2"));
        // The attempt is over: a SESSION_OK after the error opens nothing.
        assert!(m.handle(Command::Packet(session_ok()), NOW).is_empty());
    }

    #[test]
    fn retry_keeps_the_nonce_then_fails() {
        let mut m = Machine::new();
        let first = sent(&start(&mut m)).clone();
        for _ in 0..3 {
            let again = sent(&m.handle(Command::Tick, NOW)).clone();
            assert_eq!(
                first.body, again.body,
                "the retry must carry the same nonce"
            );
            assert_eq!(first.header.packet_type, PacketType::Hello);
        }
        let failed = m.handle(Command::Tick, NOW);
        assert!(
            failed
                .iter()
                .any(|a| matches!(a, Action::Failed(s) if s == "handshake timeout"))
        );
        assert!(!format!("{failed:?}").contains(PSK));
    }

    #[test]
    fn bad_proof_does_not_echo_the_secret() {
        let mut m = Machine::new();
        let _ = start(&mut m);
        let mut challenge = challenge();
        let Body::Challenge { proof_b, .. } = &mut challenge.body else {
            unreachable!()
        };
        *proof_b = [9u8; PROOF_LEN];
        let actions = m.handle(Command::Packet(challenge), NOW);
        match &actions[..] {
            [Action::Failed(text)] => {
                assert_eq!(text, "bad proof");
                assert!(!text.contains(PSK));
            }
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn empty_secret_fails_before_hello() {
        let mut m = Machine::new();
        let actions = m.handle(
            Command::Start {
                nonce_a: nonce_a(),
                psk: String::new(),
                hello_retries: 3,
            },
            NOW,
        );
        assert!(matches!(&actions[..], [Action::Failed(text)] if text == "empty psk"));
        assert!(m.handle(Command::Tick, NOW).is_empty());
    }

    #[test]
    fn a_second_start_is_ignored() {
        let mut m = Machine::new();
        establish(&mut m);
        assert!(
            m.handle(
                Command::Start {
                    nonce_a: nonce_a(),
                    psk: PSK.into(),
                    hello_retries: 3,
                },
                NOW
            )
            .is_empty()
        );
    }

    #[test]
    fn debug_omits_the_secret() {
        let mut m = Machine::new();
        let _ = start(&mut m);
        assert!(!format!("{m:?}").contains(PSK));
    }

    #[test]
    fn a_session_ok_without_a_challenge_is_ignored() {
        let mut m = Machine::new();
        let _ = start(&mut m);
        let actions = m.handle(Command::Packet(session_ok()), NOW);
        assert!(actions.is_empty());
    }

    #[test]
    fn a_broken_datagram_is_dropped_silently() {
        let mut m = Machine::new();
        // During the handshake a broken frame is dropped silently.
        let _ = start(&mut m);
        assert!(m.on_datagram(&[0u8; 3], NOW).is_empty());
        // And after the handshake the frames of part C are not read yet.
        let challenge = challenge();
        let _ = m.handle(Command::Packet(challenge), NOW);
        let ok = m.handle(Command::Packet(session_ok()), NOW);
        assert!(ok.iter().any(|a| matches!(a, Action::Established { .. })));
        assert!(m.on_datagram(&[0u8; 3], NOW).is_empty());
    }
}
