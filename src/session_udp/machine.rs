//! UDP Session state machine.
//!
//! Pure logic module: no gpui, no tokio, and no clock or random source of its
//! own. Time arrives from outside (`now`, Unix seconds) and so do the random
//! bytes (the 32-byte handshake nonce and the 5-byte nonce tail). The whole
//! machine is therefore deterministic and testable without a network.
//!
//! Handshake (protocol §5.4, spec B):
//! `HELLO` → `CHALLENGE` → `RESPONSE` → `SESSION_OK`, or `SESSION_ERR`.
//! Session (spec C): encrypted `DATA`, `PUSH` and `CLOSE`.
//! Answers (spec E): the plain text of a `DATA` frame is parsed as the
//! envelope of a business message, and the answer is correlated with the
//! command it belongs to.

use crate::session_udp::codec::{
    Body, DIRECTION_APP_TO_ESP, DIRECTION_ESP_TO_APP, Envelope, Frame, HANDSHAKE_NONCE_LEN,
    HKDF_INFO, Header, MAX_PLAINTEXT, MSG_TYPE_ACK, MSG_TYPE_ERROR, PacketType,
    TIMESTAMP_WINDOW_SECONDS, build_nonce, decode, header_bytes, nonce_matches, proof_a_input,
    proof_b_input,
};
use crate::session_udp::crypto::{
    aes_gcm_decrypt, aes_gcm_encrypt, hkdf_sha256, hmac_sha256, hmac_verify,
};
use std::fmt;

/// Body of the outgoing `CLOSE`: the client only closes on an explicit
/// disconnect, and the reason says so (protocol §5.9).
const CLOSE_BODY_USER_DISCONNECT: &[u8] = br#"{"reason":"user_disconnect"}"#;

/// Results that finish a command (protocol §2.5.2).
///
/// The other results (`received`, `scheduled`) are intermediate: the final
/// answer of the command is still to come.
const TERMINAL_RESULTS: &[&str] = &["applied", "failed", "rejected", "expired", "superseded"];

/// How many commands the client remembers while it waits for their answers.
const MAX_PENDING_COMMANDS: usize = 32;

/// State machine input.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Command {
    /// Start the handshake: client nonce, pre-shared secret, HELLO resend count.
    Start {
        /// 32 random bytes, generated by the caller.
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        /// Pre-shared secret; its bytes are the HMAC key as they are.
        psk: String,
        /// Resend count after the first HELLO.
        hello_retries: u8,
    },
    /// Handshake timeout, driven by an external timer.
    Tick,
    /// A frame that arrived.
    Packet(Frame),
    /// Bytes the user wants to send.
    UserBytes {
        /// Payload; it goes into the body of a `DATA` frame as it is.
        bytes: Vec<u8>,
        /// Five random bytes for the tail of the nonce.
        nonce_tail: [u8; 5],
    },
    /// The user disconnected.
    UserDisconnect {
        /// Five random bytes for the tail of the nonce.
        nonce_tail: [u8; 5],
    },
}

/// A command of the application that waits for an answer (protocol §2.1).
///
/// The client remembers the commands it sends as envelopes: the answer of the
/// device names the command in `correlation_id`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PendingCommand {
    /// The `msg_id` of the command.
    pub msg_id: String,
    /// The name of the command, when the envelope carries `payload.cmd`.
    pub cmd: Option<String>,
}

/// What the device answered (protocol §2.5.2, §2.5.3).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReplyOutcome {
    /// The device confirmed the command: "applied", "rejected", ...
    Ack {
        /// The result of the answer.
        result: Option<String>,
    },
    /// The device refused the command: "E_INVALID_CMD", ...
    Error {
        /// The code of the error.
        code: Option<String>,
    },
}

/// An answer of the device, bound to the command it belongs to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CommandReply {
    /// What the device answered.
    pub outcome: ReplyOutcome,
    /// The command the answer belongs to; known when the correlation matched.
    pub command: Option<PendingCommand>,
}

/// State machine output.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Action {
    /// A frame that has to go out.
    Send(Frame),
    /// Decrypted plaintext.
    Deliver(Vec<u8>),
    /// The handshake is over, the session is open.
    Established {
        /// Session id of the open session.
        session_id: u16,
    },
    /// Fatal failure: the connection ends.
    Failed(String),
    /// The session is closed. The reason is set when the peer closed it.
    Closed {
        /// Reason from the peer, `None` when the client closed the session.
        reason: Option<String>,
    },
    /// Non-fatal warning: the session stays alive.
    Warn(String),
    /// The device answered a command (protocol §2.5.2, §2.5.3).
    ///
    /// The plain text of the frame goes to the journal as well: this action
    /// carries the parsed answer, not the text.
    Reply(CommandReply),
}

/// Internal state.
enum State {
    Idle,
    /// Handshake in progress. The nonce stays the same across retries.
    Handshake {
        /// The client nonce of this attempt.
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        /// Pre-shared secret, kept until the session key is derived.
        psk: String,
        /// Resends left after the first HELLO.
        tries_left: u8,
        /// Nonce of the challenge that was answered; the session key needs it.
        nonce_b: Option<[u8; HANDSHAKE_NONCE_LEN]>,
    },
    /// The session is open.
    Established {
        /// Session id of the open session.
        session_id: u16,
        /// Session key.
        key: [u8; 32],
        /// Sequence number of the next outgoing frame.
        tx_seq: u32,
        /// Sequence number of the last accepted frame.
        rx_seq: Option<u32>,
        /// The commands that wait for an answer.
        pending: Vec<PendingCommand>,
    },
    Closed,
    Failed,
}

/// UDP Session state machine.
pub struct Machine {
    state: State,
}

impl Machine {
    /// A machine that has not started yet.
    pub fn new() -> Self {
        Machine { state: State::Idle }
    }

    /// Handle one input and return the actions it produced.
    ///
    /// `now` is the Unix second the client clock reads; it fills the timestamp
    /// of outgoing frames and bounds the replay window of incoming ones.
    pub fn handle(&mut self, cmd: Command, now: u32) -> Vec<Action> {
        match cmd {
            Command::Start {
                nonce_a,
                psk,
                hello_retries,
            } => self.on_start(nonce_a, psk, hello_retries, now),
            Command::Tick => self.on_tick(now),
            Command::Packet(frame) => self.on_packet(frame, now),
            Command::UserBytes { bytes, nonce_tail } => self.on_user_bytes(bytes, nonce_tail, now),
            Command::UserDisconnect { nonce_tail } => self.on_user_disconnect(nonce_tail, now),
        }
    }

    /// Handle one received datagram: parse it first, and decide by the current
    /// state whether a broken frame is a failure or is dropped silently.
    pub fn on_datagram(&mut self, bytes: &[u8], now: u32) -> Vec<Action> {
        match decode(bytes) {
            Ok(frame) => self.handle(Command::Packet(frame), now),
            // A frame that cannot be parsed is dropped: the device stays silent
            // on garbage too, and answering it would only feed a noise peer.
            Err(_) => {
                if matches!(self.state, State::Established { .. }) {
                    vec![Action::Warn("bad datagram".to_string())]
                } else {
                    Vec::new()
                }
            }
        }
    }

    /// Start the handshake: only from `Idle`.
    fn on_start(
        &mut self,
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        psk: String,
        hello_retries: u8,
        now: u32,
    ) -> Vec<Action> {
        if !matches!(self.state, State::Idle) {
            return Vec::new();
        }
        // An empty secret is not a key: the attempt fails before a single byte
        // reaches the network.
        if psk.is_empty() {
            self.state = State::Failed;
            return vec![Action::Failed("empty psk".to_string())];
        }
        self.state = State::Handshake {
            nonce_a,
            psk,
            tries_left: hello_retries,
            nonce_b: None,
        };
        vec![Action::Send(Self::hello_frame(nonce_a, now))]
    }

    /// Handshake timeout: resend the same HELLO, and fail when the resends are
    /// used up.
    fn on_tick(&mut self, now: u32) -> Vec<Action> {
        let (nonce_a, tries_left) = match &self.state {
            State::Handshake {
                nonce_a,
                tries_left,
                ..
            } => (*nonce_a, *tries_left),
            _ => return Vec::new(),
        };
        if tries_left == 0 {
            self.state = State::Failed;
            return vec![Action::Failed("handshake timeout".to_string())];
        }
        if let State::Handshake {
            tries_left,
            nonce_b,
            ..
        } = &mut self.state
        {
            *tries_left -= 1;
            // The resend restarts the attempt: the device replaces its
            // challenge, so the answered challenge is not valid any more.
            *nonce_b = None;
        }
        vec![Action::Send(Self::hello_frame(nonce_a, now))]
    }

    /// The HELLO frame of an attempt.
    fn hello_frame(nonce_a: [u8; HANDSHAKE_NONCE_LEN], now: u32) -> Frame {
        Frame {
            header: Header {
                packet_type: PacketType::Hello,
                session_id: 0,
                seq: 0,
                timestamp: now,
            },
            body: Body::Hello { nonce_a },
        }
    }

    /// A frame that arrived: dispatch by the current state.
    fn on_packet(&mut self, frame: Frame, now: u32) -> Vec<Action> {
        if matches!(self.state, State::Handshake { .. }) {
            let (nonce_a, psk, tries_left, nonce_b) =
                match std::mem::replace(&mut self.state, State::Idle) {
                    State::Handshake {
                        nonce_a,
                        psk,
                        tries_left,
                        nonce_b,
                    } => (nonce_a, psk, tries_left, nonce_b),
                    other => {
                        self.state = other;
                        return Vec::new();
                    }
                };
            let (state, actions) =
                Self::handshake_packet(frame, nonce_a, psk, tries_left, nonce_b, now);
            self.state = state;
            actions
        } else if matches!(self.state, State::Established { .. }) {
            self.established_packet(frame, now)
        } else {
            Vec::new()
        }
    }

    /// A frame that arrived while the handshake is running.
    fn handshake_packet(
        frame: Frame,
        nonce_a: [u8; HANDSHAKE_NONCE_LEN],
        psk: String,
        tries_left: u8,
        nonce_b: Option<[u8; HANDSHAKE_NONCE_LEN]>,
        now: u32,
    ) -> (State, Vec<Action>) {
        match frame.body {
            Body::Challenge {
                nonce_b: device_nonce,
                proof_b,
            } => {
                // The device proves that it knows the secret. Without this
                // check the client would answer a stranger.
                let input = proof_b_input(&nonce_a, &device_nonce);
                if !hmac_verify(psk.as_bytes(), &input, &proof_b) {
                    return (State::Failed, vec![Action::Failed("bad proof".to_string())]);
                }
                // The client proves the same, with the other context byte.
                let proof_a = hmac_sha256(psk.as_bytes(), &proof_a_input(&device_nonce, &nonce_a));
                let response = Frame {
                    header: Header {
                        packet_type: PacketType::Response,
                        session_id: 0,
                        seq: 0,
                        timestamp: now,
                    },
                    body: Body::Response { proof_a },
                };
                (
                    State::Handshake {
                        nonce_a,
                        psk,
                        tries_left,
                        nonce_b: Some(device_nonce),
                    },
                    vec![Action::Send(response)],
                )
            }
            Body::SessionOk => {
                // The session key needs the nonce of the challenge that was
                // answered. A SESSION_OK without a challenge is not ours.
                let Some(device_nonce) = nonce_b else {
                    return (
                        State::Handshake {
                            nonce_a,
                            psk,
                            tries_left,
                            nonce_b,
                        },
                        Vec::new(),
                    );
                };
                let mut salt = Vec::with_capacity(HANDSHAKE_NONCE_LEN * 2);
                salt.extend_from_slice(&nonce_a);
                salt.extend_from_slice(&device_nonce);
                let key = hkdf_sha256(psk.as_bytes(), &salt, HKDF_INFO);
                let session_id = frame.header.session_id;
                (
                    State::Established {
                        session_id,
                        key,
                        // The device numbers its own frames from 1, so the
                        // client starts there too.
                        tx_seq: 1,
                        rx_seq: None,
                        // No command has been sent yet.
                        pending: Vec::new(),
                    },
                    vec![Action::Established { session_id }],
                )
            }
            Body::SessionErr { code } => (
                State::Failed,
                vec![Action::Failed(format!("session err {code}"))],
            ),
            // Every other frame is a passer-by: it does not belong to the
            // handshake and is dropped silently.
            _ => (
                State::Handshake {
                    nonce_a,
                    psk,
                    tries_left,
                    nonce_b,
                },
                Vec::new(),
            ),
        }
    }

    /// A frame that arrived while the session is open.
    fn established_packet(&mut self, frame: Frame, now: u32) -> Vec<Action> {
        let (session_id, key) = match &self.state {
            State::Established {
                session_id, key, ..
            } => (*session_id, *key),
            _ => return Vec::new(),
        };
        let Body::Encrypted { nonce, ciphertext } = &frame.body else {
            return vec![Action::Warn("unexpected packet".to_string())];
        };
        // The session id decides first: a frame of another session must not be
        // reported as a broken tag.
        if frame.header.session_id != session_id {
            return vec![Action::Warn("foreign session".to_string())];
        }
        // The nonce names the session, the direction and the sequence number.
        if !nonce_matches(nonce, session_id, DIRECTION_ESP_TO_APP, frame.header.seq) {
            return vec![Action::Warn("bad nonce".to_string())];
        }
        // The replay window of the header timestamp (protocol §5.7).
        if Self::seconds_apart(now, frame.header.timestamp) >= TIMESTAMP_WINDOW_SECONDS {
            return vec![Action::Warn("timestamp out of window".to_string())];
        }
        // The sequence number of the device has to grow. The first frame may
        // carry any number.
        let rx_seq = match &self.state {
            State::Established { rx_seq, .. } => *rx_seq,
            _ => None,
        };
        if let Some(last) = rx_seq {
            if frame.header.seq <= last {
                return vec![Action::Warn("bad seq".to_string())];
            }
        }
        // The tag is the last check; the AAD is the header of the frame.
        let aad = header_bytes(&frame.header);
        let plain = match aes_gcm_decrypt(&key, nonce, &aad, ciphertext) {
            Ok(plain) => plain,
            Err(_) => return vec![Action::Warn("bad tag".to_string())],
        };
        // The frame is accepted: the receive counter moves.
        if let State::Established { rx_seq, .. } = &mut self.state {
            *rx_seq = Some(frame.header.seq);
        }
        match frame.header.packet_type {
            PacketType::Data => {
                // The plain text goes into the journal as it is, and the
                // answer of the device is parsed aside: an "ack" or an
                // "error" is a reply to a command.
                let reply = self.take_reply(&plain);
                let mut actions = vec![Action::Deliver(plain)];
                if let Some(reply) = reply {
                    actions.push(Action::Reply(reply));
                }
                actions
            }
            PacketType::Push => {
                // The body of a push is not parsed: the snapshots and the
                // events are not in the scope of the client yet (spec F).
                vec![Action::Deliver(plain)]
            }
            PacketType::Close => {
                // The peer closed the session: the reason is read from the
                // decrypted body, and an unreadable body does not keep the
                // session alive.
                let reason = Some(Self::close_reason(&plain));
                self.state = State::Closed;
                vec![Action::Closed { reason }]
            }
            _ => vec![Action::Warn("unexpected packet".to_string())],
        }
    }

    /// The reason of an incoming `CLOSE`: `{"reason":"..."}` (protocol §5.9).
    ///
    /// An unreadable body yields an empty reason; the session is closed
    /// anyway, because the frame did arrive and its tag did match.
    fn close_reason(plain: &[u8]) -> String {
        serde_json::from_slice::<serde_json::Value>(plain)
            .ok()
            .and_then(|value| {
                value
                    .get("reason")
                    .and_then(|reason| reason.as_str())
                    .map(str::to_string)
            })
            .unwrap_or_default()
    }

    /// Remember a command of the application: the answer of the device names
    /// its `msg_id` in `correlation_id` (protocol §2.1).
    ///
    /// The bytes go to the wire as they are: the envelope is not rebuilt and
    /// no field is added.
    fn remember_command(&mut self, bytes: &[u8]) {
        let Some(envelope) = Envelope::parse(bytes) else {
            return;
        };
        if !envelope.is_command() {
            return;
        }
        let cmd = envelope.command_name().map(str::to_string);
        let Some(msg_id) = envelope.msg_id.filter(|id| !id.is_empty()) else {
            return;
        };
        let command = PendingCommand { msg_id, cmd };
        let State::Established { pending, .. } = &mut self.state else {
            return;
        };
        // The same `msg_id` twice: the newer command replaces the older one.
        pending.retain(|known| known.msg_id != command.msg_id);
        // The list is bounded: a command without an answer does not grow it
        // forever.
        if pending.len() >= MAX_PENDING_COMMANDS {
            pending.remove(0);
        }
        pending.push(command);
    }

    /// The answer of the device, parsed from the plain text of a `DATA` frame.
    ///
    /// The answer is bound to the command it belongs to: the `correlation_id`
    /// of the answer names the `msg_id` of the command.
    fn take_reply(&mut self, plain: &[u8]) -> Option<CommandReply> {
        let envelope = Envelope::parse(plain)?;
        let outcome = match envelope.msg_type.as_str() {
            MSG_TYPE_ACK => ReplyOutcome::Ack {
                result: envelope.result().map(str::to_string),
            },
            MSG_TYPE_ERROR => ReplyOutcome::Error {
                code: envelope.error_code().map(str::to_string),
            },
            _ => return None,
        };
        let command = envelope
            .correlation_id
            .as_deref()
            .and_then(|correlation_id| self.take_pending(correlation_id, &outcome));
        Some(CommandReply { outcome, command })
    }

    /// Take the remembered command with this `msg_id`.
    ///
    /// A command is answered for good only by a terminal result or by an
    /// error: an intermediate result leaves the command waiting for its final
    /// answer (protocol §2.5.2).
    fn take_pending(&mut self, msg_id: &str, outcome: &ReplyOutcome) -> Option<PendingCommand> {
        let State::Established { pending, .. } = &mut self.state else {
            return None;
        };
        let index = pending.iter().position(|known| known.msg_id == msg_id)?;
        let terminal = match outcome {
            ReplyOutcome::Error { .. } => true,
            ReplyOutcome::Ack { result } => result
                .as_deref()
                .is_some_and(|result| TERMINAL_RESULTS.contains(&result)),
        };
        if terminal {
            return Some(pending.remove(index));
        }
        // The command is not answered for good: it stays in the list.
        Some(pending[index].clone())
    }

    /// The difference of two timestamps, in seconds; the difference fits in
    /// 32 bits.
    fn seconds_apart(a: u32, b: u32) -> u32 {
        let diff = (a as i64) - (b as i64);
        diff.unsigned_abs() as u32
    }

    /// Encrypt a payload into an outgoing frame.
    fn encrypt_frame(
        packet_type: PacketType,
        key: &[u8; 32],
        session_id: u16,
        seq: u32,
        nonce_tail: [u8; 5],
        now: u32,
        plain: &[u8],
    ) -> Frame {
        let header = Header {
            packet_type,
            session_id,
            seq,
            timestamp: now,
        };
        // The client is the application side, so its direction byte is 0x00.
        let nonce = build_nonce(session_id, DIRECTION_APP_TO_ESP, seq, nonce_tail);
        let aad = header_bytes(&header);
        // The key and the nonce have fixed lengths, so encryption only fails on
        // a defect of the implementation.
        let ciphertext = aes_gcm_encrypt(key, &nonce, &aad, plain)
            .expect("AES-256-GCM key and nonce have fixed lengths, encryption cannot fail");
        Frame {
            header,
            body: Body::Encrypted { nonce, ciphertext },
        }
    }

    /// The user sends bytes: they go into the body of a `DATA` frame as they
    /// are, without any parsing.
    fn on_user_bytes(&mut self, bytes: Vec<u8>, nonce_tail: [u8; 5], now: u32) -> Vec<Action> {
        let (session_id, key, tx_seq) = match &self.state {
            State::Established {
                session_id,
                key,
                tx_seq,
                ..
            } => (*session_id, *key, *tx_seq),
            _ => return vec![Action::Warn("not established".to_string())],
        };
        // An empty body is not sent and does not spend a sequence number.
        if bytes.is_empty() {
            return Vec::new();
        }
        // A payload that does not fit into one datagram never reaches the
        // wire, and it does not spend a sequence number either.
        if bytes.len() > MAX_PLAINTEXT {
            return vec![Action::Warn("payload too large".to_string())];
        }
        // The counter is never wrapped: at the ceiling the session ends.
        if tx_seq == u32::MAX {
            self.state = State::Failed;
            return vec![Action::Failed("seq exhausted".to_string())];
        }
        // A command envelope is remembered: the answer of the device names
        // its `msg_id` in `correlation_id` (protocol §2.1).
        self.remember_command(&bytes);
        let frame = Self::encrypt_frame(
            PacketType::Data,
            &key,
            session_id,
            tx_seq,
            nonce_tail,
            now,
            &bytes,
        );
        if let State::Established { tx_seq, .. } = &mut self.state {
            *tx_seq += 1;
        }
        vec![Action::Send(frame)]
    }

    /// The user disconnects: send an encrypted `CLOSE` and end the session.
    fn on_user_disconnect(&mut self, nonce_tail: [u8; 5], now: u32) -> Vec<Action> {
        let state = std::mem::replace(&mut self.state, State::Idle);
        match state {
            State::Established {
                session_id,
                key,
                tx_seq,
                ..
            } => {
                let mut actions = Vec::new();
                // A spent counter means no `CLOSE` goes out, but the session
                // still ends.
                if tx_seq != u32::MAX {
                    let frame = Self::encrypt_frame(
                        PacketType::Close,
                        &key,
                        session_id,
                        tx_seq,
                        nonce_tail,
                        now,
                        CLOSE_BODY_USER_DISCONNECT,
                    );
                    actions.push(Action::Send(frame));
                }
                self.state = State::Closed;
                actions.push(Action::Closed { reason: None });
                actions
            }
            State::Handshake { .. } => {
                self.state = State::Closed;
                vec![Action::Closed { reason: None }]
            }
            state => {
                self.state = state;
                Vec::new()
            }
        }
    }

    /// Test helper: move the send counter (only in an open session).
    #[cfg(test)]
    fn test_set_tx_seq(&mut self, seq: u32) {
        if let State::Established { tx_seq, .. } = &mut self.state {
            *tx_seq = seq;
        }
    }
}

impl Default for Machine {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Debug for Machine {
    /// Only the state name and the counters are printed: secret, key, nonce
    /// and proof never reach the log.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.state {
            State::Idle => write!(f, "Machine(Idle)"),
            State::Handshake { tries_left, .. } => {
                write!(f, "Machine(Handshake, tries_left={tries_left})")
            }
            State::Established { tx_seq, rx_seq, .. } => write!(
                f,
                "Machine(Established, tx_seq={tx_seq}, rx_seq={rx_seq:?})"
            ),
            State::Closed => write!(f, "Machine(Closed)"),
            State::Failed => write!(f, "Machine(Failed)"),
        }
    }
}

